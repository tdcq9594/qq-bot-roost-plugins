  "",
  "function render() {",
  "  const box = $('#list');",
  "  box.textContent = '';",
  "  $('#count').textContent = cards.length + ' 张人设卡' + (cards.length > 1 ? '（取第一张，或用 defaultCard 指定）' : '');",
