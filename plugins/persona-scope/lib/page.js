/**
 * 预设管理页（面板内 iframe）
 *
 * 形态对齐 RP-Hub 的「预设管理」：可排序的列表，每条有名称、角色徽章、启用开关、
 * 编辑与删除，顶部可新建 / 导入 / 导出 JSON。
 *
 * 页面是独立的 iframe（allow-scripts allow-same-origin，CSS 不外漏），
 * 通过同源 fetch 调自己的 REST 接口拿数据、写数据。
 *
 * ⚠️ 写操作必须带 `Content-Type: application/json`：
 * 框架在路由之前有一道 isJsonRequest 校验，缺了直接 415 且页面只看到 Failed to fetch。
 */

