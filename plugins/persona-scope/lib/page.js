  "",
  "async function load() {",
  "  try {",
  "    const r = await fetch(API);",
  "    if (!r.ok) throw new Error('HTTP ' + r.status);",
  "    const j = await r.json();",
  "    cards = Array.isArray(j.cards) ? j.cards : [];",
  "    maxChars = Number(j.maxChars) || 1200;",
  "    presetTotal = Number(j.presetTotal) || 0;",
  "    render(); renderBudget();",
