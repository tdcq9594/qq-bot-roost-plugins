  "    say('已保存（下一轮消息生效）');",
  "    renderBudget();",
  "  } catch (e) { say('保存失败：' + e.message, true); }",
  "}",
  "",
  "async function saveMaxChars(v) {",
  "  try {",
  "    const r = await fetch(SET, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ maxChars: v }) });",
  "    if (!r.ok) throw new Error('HTTP ' + r.status);",
  "    maxChars = v; say('预算已改为 ' + v + ' 字'); renderBudget(); render();",
